"""Иерархия ошибок приложения (см. docs/ARCHITECTURE.md §9).

В фазе 1 добавлено разделение на временные и постоянные ошибки задачи: от него зависит,
ретраится задача или сразу считается упавшей. В фазе 2 сюда переехали ошибки edu-tpi:
клиент (`bot/integrations/edu_tpi.py`) больше не заводит собственные классы-двойники.
"""

from __future__ import annotations


class AppError(Exception):
    """Базовая ошибка приложения."""


class ConfigError(AppError):
    """Некорректная или неполная конфигурация: с ней бот не должен запускаться."""


class RetryableError(AppError):
    """Временная ошибка задачи: имеет смысл повторить.

    Сеть, таймаут, 5xx, 429 — задача ретраится автоматически (`BaseTask.autoretry_for`)
    с backoff до `max_retries` раз (docs/ARCHITECTURE.md §9).
    """


class PermanentError(AppError):
    """Постоянная ошибка задачи: повтор не поможет.

    Неверные данные, изменившаяся схема ответа, отсутствующий пользователь — задачу
    нужно залогировать как `ERROR` и не ретраить (иначе повторы только забьют очередь).
    """


class EduError(AppError):
    """Базовая ошибка интеграции с edu-tpi."""


class EduAuthError(EduError):
    """Логин или пароль не подошли (400/401/403 на входе, нет `accessToken`).

    Это постоянная ошибка: повтор того же запроса бессмысленен, пользователь должен
    войти заново.
    """


class EduTokenExpired(EduError):  # noqa: N818 — имя зафиксировано в docs/ARCHITECTURE.md §9
    """401 на защищённом методе: токен истёк или отозван.

    Обрабатывается переавторизацией по сохранённым данным (`TokenService.call`), а не
    показом ошибки пользователю.
    """


class EduUnavailableError(EduError):
    """edu-tpi недоступен: сеть, таймаут или 5xx. Задачу имеет смысл повторить."""


class EduRateLimitError(EduError):
    """429 от edu-tpi: слишком много запросов.

    `retry_after` — пауза из заголовка `Retry-After`, если сервер её прислал.
    """

    def __init__(self, message: str, *, retry_after: int | None = None) -> None:
        super().__init__(message)
        self.retry_after = retry_after


class ParseError(EduError):
    """Ответ пришёл, но его структура не та, что ожидает клиент.

    Повтор не поможет: изменилась схема API или данные повреждены. Задача не
    ретраится, пользователь видит «не удалось разобрать журнал».
    """


class EduEmptyJournalError(EduError):
    """Журнал существует в списке, но данных по нему нет (`state < 0`, `data: null`).

    Это не ошибка схемы и не сбой: такие журналы встречаются у архивных дисциплин.
    Синхронизация пропускает их и не считает ошибкой.
    """
